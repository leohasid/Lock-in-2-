export function recipeCardImageSrc(recipeId: string): string | null {
  return PHOTO_IDS.has(recipeId) ? `/images/recipes/${recipeId}.png` : null;
}

function r(
  base: Omit<Recipe, "calories"> & { protein: number; carbs: number; fats: number }
): Recipe {
  const { protein, carbs, fats, ...rest } = base;
  return {
    ...rest,
    protein,
    carbs,
    fats,
    calories: kcalFromMacros(protein, carbs, fats),
  };
}


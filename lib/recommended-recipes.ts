/**
 * Built-in recommended recipes. Calories = round(4×protein + 4×carbs + 9×fats) kcal
 * so totals match the displayed macros (Atwater general factors).
 */

export interface Recipe {
  id: string;
  name: string;
  calories: number;
  protein: number;
  carbs: number;
  fats: number;
  sugar?: number;
  sodium?: number;
  fiber?: number;
  description: string;
  category: string;
  prepTime?: string;
  servings?: number;
  /** Built-in recipes always include these; personal saved recipes may omit */
  ingredients?: string[];
  steps?: string[];
}

export function kcalFromMacros(protein: number, carbs: number, fats: number): number {
  return Math.round(protein * 4 + carbs * 4 + fats * 9);
}

